#!/usr/bin/env node
/*
 * Step-by-step guides for moderators: docs/runbook-<id>.md -> content/guide-<id>.html
 *
 * The runbooks used to live only in the repo, so a moderator never saw them
 * (Rafa, 03.11.2026: «all support material, it's so hidden now»). This turns each
 * one into a page on the site, linked from the session's Moderator kit.
 *
 *   npm run guides            render every docs/runbook-*.md
 *
 * Dependency-free: a small Markdown subset is enough for the runbooks — headings,
 * paragraphs, lists and checklists, tables, quotes, **bold**, *italic*, `code`,
 * [links](…) and <https://…>. Links stay relative: docs/ and content/ sit at the
 * same depth, so ../slides/… keeps working; a link into docs/ itself is rewritten.
 * Also run by `npm run build`, so a merged runbook always gets its page.
 */
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const esc = s => String(s).replace(/[&<>"]/g, c => ({ "&":"&amp;", "<":"&lt;", ">":"&gt;", '"':"&quot;" }[c]));

function href(u){
  if (/^(https?:|mailto:|#|\.\.\/)/.test(u)) return u;
  return "../docs/" + u;                      // e.g. reference/x.pdf, relative to docs/
}
function inline(s){
  const codes = [];
  s = s.replace(/`([^`]+)`/g, (_, c) => { codes.push(c); return `\u0000${codes.length - 1}\u0000`; });
  s = esc(s);
  s = s.replace(/&lt;(https?:\/\/[^\s&]+)&gt;/g, (_, u) => `<a href="${u}">${u.replace(/^https?:\/\//, "").replace(/\/$/, "")}</a>`);
  s = s.replace(/\[([^\]]+)\]\(([^)\s]+)\)/g, (_, t, u) => `<a href="${esc(href(u))}">${t}</a>`);
  s = s.replace(/\*\*([^*]+)\*\*/g, "<b>$1</b>");
  s = s.replace(/(^|[^*\w])\*([^*\s][^*]*)\*(?!\w)/g, "$1<i>$2</i>");
  s = s.replace(/\u0000(\d+)\u0000/g, (_, i) => `<code>${esc(codes[+i])}</code>`);
  return s;
}

function md(src){
  const lines = src.replace(/\r/g, "").split("\n");
  const out = [];
  let i = 0, title = "";
  const para = [];
  const flush = () => { if (para.length) { out.push(`<p>${inline(para.join(" "))}</p>`); para.length = 0; } };
  while (i < lines.length) {
    const l = lines[i];
    if (!l.trim()) { flush(); i++; continue; }
    let m;
    if ((m = l.match(/^(#{1,4})\s+(.*)$/))) {
      flush();
      const n = m[1].length;
      if (n === 1 && !title) { title = m[2]; i++; continue; }
      out.push(`<h${n}>${inline(m[2])}</h${n}>`); i++; continue;
    }
    if (/^\|/.test(l)) {
      flush();
      const rows = [];
      while (i < lines.length && /^\|/.test(lines[i])) { rows.push(lines[i]); i++; }
      const cells = r => r.replace(/^\||\|$/g, "").split("|").map(c => c.trim());
      const head = cells(rows[0]), body = rows.slice(2).map(cells);
      out.push(`<div class="tbl"><table><thead><tr>${head.map(c => `<th>${inline(c)}</th>`).join("")}</tr></thead><tbody>` +
        body.map(r => `<tr>${r.map((c, k) => `<td data-h="${esc(head[k] || "")}">${inline(c)}</td>`).join("")}</tr>`).join("") +
        `</tbody></table></div>`);
      continue;
    }
    if (/^>\s?/.test(l)) {
      flush();
      const q = [];
      while (i < lines.length && /^>\s?/.test(lines[i])) { q.push(lines[i].replace(/^>\s?/, "")); i++; }
      out.push(`<blockquote>${inline(q.join(" "))}</blockquote>`);
      continue;
    }
    if ((m = l.match(/^(\s*)([-*]|\d+\.)\s+(.*)$/))) {
      flush();
      const ordered = /\d/.test(m[2]);
      const items = [];
      while (i < lines.length) {
        const x = lines[i].match(/^(\s*)([-*]|\d+\.)\s+(.*)$/);
        if (x && x[1].length < 2) { items.push(x[3]); i++; continue; }
        if (lines[i].trim() && /^\s{2,}/.test(lines[i]) && items.length) { items[items.length - 1] += " " + lines[i].trim(); i++; continue; }
        break;
      }
      const tag = ordered ? "ol" : "ul";
      out.push(`<${tag}>${items.map(t => {
        const box = t.match(/^\[( |x)\]\s+(.*)$/i);
        return box ? `<li class="todo"><span class="box" aria-hidden="true">${box[1].trim() ? "☑" : "☐"}</span><span>${inline(box[2])}</span></li>`
                   : `<li>${inline(t)}</li>`;
      }).join("")}</${tag}>`);
      continue;
    }
    para.push(l.trim()); i++;
  }
  flush();
  return { title, body: out.join("\n") };
}

